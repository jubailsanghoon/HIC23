    _wpsCache: null,
    _welderCache: null,

    isProUser: function() {
        if (typeof MainController !== 'undefined' && typeof MainController.isPro !== 'undefined') {
            return Boolean(MainController.isPro);
        }
        return false;
    },

    getMaxLimit: function() {
        return this.isProUser() ? 300 : 10;
    },

    getWpsPresets: function() {
        const isPro = this.isProUser();
        if (!this._wpsCache) {
            try {
                const sampleApplied = localStorage.getItem('HI_WPS_SAMPLE10_V23_ARB') === 'true';
                const saved = localStorage.getItem('HI_WPS_PRESETS');
                const parsed = saved ? JSON.parse(saved) : null;
                if (!sampleApplied || !Array.isArray(parsed) || parsed.length === 0) {
                    this._wpsCache = this.defaultWpsPresets.map(x => ({ ...x }));
                    localStorage.setItem('HI_WPS_PRESETS', JSON.stringify(this._wpsCache));
                    localStorage.setItem('HI_WPS_SAMPLE10_V23_ARB', 'true');
                } else {
                    this._wpsCache = parsed;
                }
            } catch (e) {
                this._wpsCache = this.defaultWpsPresets.map(x => ({ ...x }));
            }
        }
        if (!isPro) {
            return this._wpsCache.slice(0, 10);
        }
        return this._wpsCache.slice(0, 300);
    },

    setWpsPresets: function(list) {
        const maxLimit = this.getMaxLimit();
        this._wpsCache = (Array.isArray(list) ? list : []).slice(0, maxLimit);
        localStorage.setItem('HI_WPS_PRESETS', JSON.stringify(this._wpsCache));
        localStorage.setItem('HI_WPS_SAMPLE10_V23_ARB', 'true');
    },

    getDefaultWelderPresets: function(lang) {
        const targetLang = lang || (typeof localStorage !== 'undefined' && localStorage.getItem('HI_LANG')) || 'ko';
        const list = this.defaultWelderPresetsByLang[targetLang] || this.defaultWelderPresetsByLang.ko;
        return list.map(x => ({ ...x }));
    },

    syncSampleWeldersForLang: function(lang) {
        try {
            if (localStorage.getItem('HI_WELDER_CUSTOMIZED') === 'true') return false;
            this._welderCache = this.getDefaultWelderPresets(lang);
            localStorage.setItem('HI_WELDER_PRESETS', JSON.stringify(this._welderCache));
            localStorage.setItem('HI_WELDER_SAMPLE10_V28_LANG', lang || 'ko');
            return true;
        } catch (e) {
            return false;
        }
    },

    getWelderPresets: function() {
        const isPro = this.isProUser();
        const lang = (typeof localStorage !== 'undefined' && localStorage.getItem('HI_LANG')) || 'ko';
        if (!this._welderCache) {
            try {
                const sampleLang = localStorage.getItem('HI_WELDER_SAMPLE10_V28_LANG');
                const isCustomized = localStorage.getItem('HI_WELDER_CUSTOMIZED') === 'true';
                const saved = localStorage.getItem('HI_WELDER_PRESETS');
                const parsed = saved ? JSON.parse(saved) : null;
                if (!Array.isArray(parsed) || parsed.length === 0 || (!isCustomized && sampleLang !== lang)) {
                    this._welderCache = this.getDefaultWelderPresets(lang);
                    localStorage.setItem('HI_WELDER_PRESETS', JSON.stringify(this._welderCache));
                    localStorage.setItem('HI_WELDER_SAMPLE10_V28_LANG', lang);
                } else {
                    this._welderCache = parsed;
                }
            } catch (e) {
                this._welderCache = this.getDefaultWelderPresets(lang);
            }
        }
        if (!isPro) {
            return this._welderCache.slice(0, 10);
        }
        return this._welderCache.slice(0, 300);
    },

    setWelderPresets: function(list, isSample) {
        const maxLimit = this.getMaxLimit();
        const lang = (typeof localStorage !== 'undefined' && localStorage.getItem('HI_LANG')) || 'ko';
        this._welderCache = (Array.isArray(list) ? list : []).slice(0, maxLimit);
        localStorage.setItem('HI_WELDER_PRESETS', JSON.stringify(this._welderCache));
        localStorage.setItem('HI_WELDER_SAMPLE10_V28_LANG', lang);
        if (!isSample) {
            localStorage.setItem('HI_WELDER_CUSTOMIZED', 'true');
        }
    }
